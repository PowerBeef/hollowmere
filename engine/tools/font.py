HEIGHT = 9


def glyph_table():
    """Returns dict char -> (width, rows as list of bitmasks LSB = leftmost)."""
    out = {}
    for ch, rows in GLYPHS.items():
        assert len(rows) == HEIGHT, (ch, len(rows))
        w = max(len(r) for r in rows)
        bits = []
        for r in rows:
            v = 0
            for i, c in enumerate(r):
                if c == '#':
                    v |= 1 << i
            bits.append(v)
        out[ch] = (w, bits)
    return out
